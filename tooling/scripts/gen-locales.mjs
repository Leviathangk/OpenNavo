// Read only the locale manifest; do not modify existing platform Locale types or translation files.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const manifest = JSON.parse(readFileSync(resolve(root, 'packages/shared/src/locales.json'), 'utf8'));
// Every locale serves the website and its content ("site"). "desktop" is the Mac client: its UI, native menus, the
// catalog data it downloads and its release notes. "app" is the admin UI and server messages, and the languages the
// website indexes without verified translations. LOCALES stays the app set; DESKTOP_LOCALES is the client's.
const codes = manifest.locales.map(locale => locale.code);
const appLocales = manifest.locales.filter(locale => locale.surfaces?.includes('app'));
const appCodes = appLocales.map(locale => locale.code);
const desktopLocales = manifest.locales.filter(locale => locale.surfaces?.includes('desktop'));
const desktopCodes = desktopLocales.map(locale => locale.code);
if (
  new Set(codes).size !== codes.length ||
  [appCodes, desktopCodes].some(set => !set.includes(manifest.defaultLocale) || !set.includes(manifest.authoringLocale))
) {
  throw new Error('Duplicate locale codes or missing default/authoring app or desktop locale in the manifest');
}
const hreflangs = manifest.locales.flatMap(locale => [locale.hreflang, ...(locale.hreflangAliases ?? [])]);
if (new Set(hreflangs.map(value => value.toLowerCase())).size !== hreflangs.length) {
  throw new Error('Duplicate hreflang values or aliases in the manifest');
}
for (const locale of manifest.locales) {
  const surfaces = locale.surfaces;
  if (
    !Array.isArray(surfaces) ||
    !surfaces.includes('site') ||
    new Set(surfaces).size !== surfaces.length ||
    surfaces.some(surface => !['site', 'app', 'desktop'].includes(surface))
  ) {
    throw new Error(`Invalid surfaces: ${locale.code}`);
  }
  const categories = locale.pluralCategories;
  if (
    !Array.isArray(categories) ||
    !categories.includes('other') ||
    new Set(categories).size !== categories.length ||
    categories.some(category => !['zero', 'one', 'two', 'few', 'many', 'other'].includes(category))
  ) {
    throw new Error(`Invalid plural categories: ${locale.code}`);
  }
}
const quote = JSON.stringify;
const goName = code => code.replace('-', '');
const rustName = code =>
  code
    .split('-')
    .map(part => part[0].toUpperCase() + part.slice(1).toLowerCase())
    .join('');
const formatted = (command, args, source) => {
  const result = spawnSync(command, args, { input: source, encoding: 'utf8', cwd: command === 'rustfmt' ? resolve(root, 'apps/desktop/src-tauri') : root });
  if (result.status !== 0) throw new Error(`${command}: ${result.stderr}`);
  return result.stdout;
};
const ts = formatted(
  'pnpm',
  ['exec', 'oxfmt', '--config', 'tooling/config/.oxfmtrc.json', '--stdin-filepath', 'packages/shared/src/locales.gen.ts'],
  `// Generated by tooling/scripts/gen-locales.mjs; edit locales.json instead.\n// App surfaces: admin UI and server messages; the website also indexes these without verified translations.\nexport const LOCALES = ${quote(appCodes)} as const;\nexport type LocaleCode = (typeof LOCALES)[number];\nexport const APP_LOCALES = LOCALES;\nexport type AppLocaleCode = LocaleCode;\n// The Mac client: its UI, native menus, downloaded catalog data and release notes.\nexport const DESKTOP_LOCALES = ${quote(desktopCodes)} as const;\nexport type DesktopLocaleCode = (typeof DESKTOP_LOCALES)[number];\n// Website and content locales (a superset of the app and desktop locales).\nexport const SITE_LOCALES = ${quote(codes)} as const;\nexport type SiteLocaleCode = (typeof SITE_LOCALES)[number];\nexport const DEFAULT_LOCALE: LocaleCode = ${quote(manifest.defaultLocale)};\nexport const AUTHORING_LOCALE: LocaleCode = ${quote(manifest.authoringLocale)};\nexport const LOCALE_METADATA = ${JSON.stringify(Object.fromEntries(manifest.locales.map(locale => [locale.code, locale])), null, 2)} as const;\n`
);
const go = formatted(
  'gofmt',
  [],
  `// Code generated by tooling/scripts/gen-locales.mjs; DO NOT EDIT.\npackage i18n\ntype LocaleCode string\nconst (\n${codes.map(code => `${goName(code)} LocaleCode = ${quote(code)}`).join('\n')}\nDefaultLocale = ${goName(manifest.defaultLocale)}\nAuthoringLocale = ${goName(manifest.authoringLocale)}\n)\n// Locales are the app surfaces: admin UI and server messages. The website indexes them without verified translations.\nvar Locales = [...]LocaleCode{${appCodes.map(goName).join(',')}}\n// DesktopLocales are the Mac client's languages: its UI, native menus, downloaded catalog data and release notes.\nvar DesktopLocales = [...]LocaleCode{${desktopCodes.map(goName).join(',')}}\n// SiteLocales are the website and content locales (a superset of Locales and DesktopLocales).\nvar SiteLocales = [...]LocaleCode{${codes.map(goName).join(',')}}\ntype LocaleMetadata struct { Name, Prefix, Hreflang, FormatLocale, Style string; PluralCategories, HreflangAliases, Surfaces []string }\nvar Metadata = map[LocaleCode]LocaleMetadata{\n${manifest.locales.map(locale => `${goName(locale.code)}: {${['name', 'prefix', 'hreflang', 'formatLocale', 'style'].map(key => quote(locale[key])).join(',')}, []string{${locale.pluralCategories.map(quote).join(',')}}, []string{${(locale.hreflangAliases ?? []).map(quote).join(',')}}, []string{${locale.surfaces.map(quote).join(',')}}},`).join('\n')}\n}\n`
);
const rust = formatted(
  'rustfmt',
  ['--emit', 'stdout', '--edition', '2024'],
  `// Generated by tooling/scripts/gen-locales.mjs; edit locales.json instead.\n// The Mac client's languages (the "desktop" surface).\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize, specta::Type)]\npub enum Locale {\n${desktopCodes.map(code => `#[serde(rename = ${quote(code)})]\n${rustName(code)},`).join('\n')}\n}\npub type LocaleCode = Locale;\npub const LOCALES: [LocaleCode; ${desktopCodes.length}] = [${desktopCodes.map(code => `LocaleCode::${rustName(code)}`).join(',')}];\npub const DEFAULT_LOCALE: LocaleCode = LocaleCode::${rustName(manifest.defaultLocale)};\npub const AUTHORING_LOCALE: LocaleCode = LocaleCode::${rustName(manifest.authoringLocale)};\npub struct LocaleMetadata { pub code: LocaleCode, pub name: &'static str, pub prefix: &'static str, pub hreflang: &'static str, pub format_locale: &'static str, pub style: &'static str, pub plural_categories: &'static [&'static str] }\npub const LOCALE_METADATA: [LocaleMetadata; ${desktopCodes.length}] = [${desktopLocales.map(locale => `LocaleMetadata {code: LocaleCode::${rustName(locale.code)}, name: ${quote(locale.name)}, prefix: ${quote(locale.prefix)}, hreflang: ${quote(locale.hreflang)}, format_locale: ${quote(locale.formatLocale)}, style: ${quote(locale.style)}, plural_categories: &[${locale.pluralCategories.map(quote).join(',')}] }`).join(',')}];\n`
);
for (const [path, content] of Object.entries({
  'packages/shared/src/locales.gen.ts': ts,
  'apps/server/internal/i18n/locales.gen.go': go,
  'apps/desktop/src-tauri/src/locales_gen.rs': rust
})) {
  const target = resolve(root, path);
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== content) throw new Error(`Generated locale file is outdated: ${path}`);
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
}
