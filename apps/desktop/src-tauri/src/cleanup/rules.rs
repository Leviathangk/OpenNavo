pub fn device_version(name: &str, platform: &str) -> Option<(String, Vec<u32>)> {
    let mut tokens = name.split_whitespace();
    let first = tokens.next()?;
    let (model, version) = if first.as_bytes().first()?.is_ascii_digit() {
        (platform, first)
    } else {
        if !first
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || c == b',')
            || !first.contains(',')
        {
            return None;
        }
        (first, tokens.next()?)
    };
    let version = version
        .split('.')
        .map(str::parse::<u32>)
        .collect::<Result<Vec<_>, _>>()
        .ok()?;
    let tail = tokens.collect::<Vec<_>>().join(" ");
    if !(tail.is_empty() || tail.starts_with('(') && tail.ends_with(')')) {
        return None;
    }
    Some((model.into(), version))
}

/// Items under a root of their own (clang's folder in the per-user OS cache, the temp folder, the Trash, device
/// backups) are judged relative to that root: its own name never blocks them, the root itself is never touched, and
/// nothing outside it or HOME is reachable. The roots come from the OS (confstr) or fixed home paths, never from
/// scanned content.
pub fn never_touch_scoped(home: &Path, path: &Path, external: Option<&Path>) -> bool {
    if let Some(root) = external.filter(|root| path.starts_with(root)) {
        never_touch(root, path)
    } else {
        never_touch(home, path)
    }
}

/// Structural safety alone: absolute, inside the root, not the root itself, no `.` or `..`, no control characters.
pub fn unsafe_location(home: &Path, path: &Path) -> bool {
    path.to_string_lossy().chars().any(char::is_control)
        || !path.is_absolute()
        || !path.starts_with(home)
        || path == home
        || path
            .components()
            .any(|c| matches!(c, Component::ParentDir | Component::CurDir))
}
/// Whether the sensitive-name rules apply to a candidate's own path. They guard folders that could be an app's data
/// store; an installer called Docker.dmg, a project called vpn-tools, an archive of an app called Cursor, an item the
/// user already put in the Trash or a device backup are none of that. Structure is always checked.
pub fn root_names_apply(reason: CleanupReason) -> bool {
    !matches!(
        reason,
        CleanupReason::Installer
            | CleanupReason::InstallerInstalled
            | CleanupReason::BuildArtifact
            | CleanupReason::XcodeArchive
            | CleanupReason::Trash
            | CleanupReason::DeviceBackup
    )
}
/// The check on a candidate's own path, at scan time and again right before it is removed.
pub fn root_blocked(
    home: &Path,
    path: &Path,
    external: Option<&Path>,
    reason: CleanupReason,
) -> bool {
    if root_names_apply(reason) {
        never_touch_scoped(home, path, external)
    } else {
        unsafe_location(
            external
                .filter(|root| path.starts_with(root))
                .unwrap_or(home),
            path,
        )
    }
}
/// Paths containing protected descendants are rejected as a whole; a parent removal must never erase a protected child.
pub fn never_touch(home: &Path, path: &Path) -> bool {
    if unsafe_location(home, path) {
        return true;
    }
    let names: Vec<_> = path
        .strip_prefix(home)
        .unwrap_or(path)
        .components()
        .map(|c| c.as_os_str().to_string_lossy().to_lowercase())
        .collect();
    const SENSITIVE: &[&str] = &[
        "keychains",
        "1password",
        "bitwarden",
        "lastpass",
        "keepass",
        "enpass",
        "dashlane",
        "clash",
        "surge",
        "tailscale",
        "wireguard",
        "networkextension",
        "vpn",
        "proxifier",
        "v2ray",
        "shadowrocket",
        "sing-box",
        "claude",
        "chatgpt",
        "cursor",
        "ollama",
        "lmstudio",
        "lm studio",
        "jan.ai",
        "docker",
        "orbstack",
        "parallels",
        "utm",
        "vmware",
        "virtualbox",
        "mobile documents",
        "photoslibrary",
        "musiclibrary",
        "timemachine",
        "time machine",
    ];
    if names
        .iter()
        .any(|n| SENSITIVE.iter().any(|s| n.contains(s)))
    {
        return true;
    }
    if names.iter().any(|n| {
        [
            ".ssh",
            ".gnupg",
            ".aws",
            ".kube",
            ".trash",
            "mail",
            "messages",
            "notes",
            "mobilesync",
            "history",
            "cookies",
            "login data",
            "local storage",
            "extensions",
            "passwords",
        ]
        .contains(&n.as_str())
    }) {
        return true;
    }
    names.iter().any(|n| {
        n.starts_with("group.com.apple.")
            || n == "com.apple.mail"
            || n == "com.apple.notes"
            || n == "com.apple.imessage"
    })
}
