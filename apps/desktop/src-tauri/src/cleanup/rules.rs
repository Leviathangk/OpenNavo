#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn device_names_and_external_clang_scope_reject_unrecognized_and_forbidden_paths() {
        assert_eq!(
            device_version("iPhone16,2 18.2 (22C152)", "iOS"),
            Some(("iPhone16,2".into(), vec![18, 2]))
        );
        assert_eq!(
            device_version("17.5 (21F79)", "iOS"),
            Some(("iOS".into(), vec![17, 5]))
        );
        for name in [
            "README",
            "iPhone16,2 invalid (B)",
            "iPhone16,2 18.2 notes",
            "../18.2",
            "18..2 (B)",
        ] {
            assert!(device_version(name, "iOS").is_none());
        }
        let home = Path::new("/synthetic/home");
        let cache = Path::new("/synthetic/cache");
        let root = cache.join("clang");
        let root = Some(root.as_path());
        assert!(!never_touch_scoped(
            home,
            &cache.join("clang/ModuleCache"),
            root
        ));
        assert!(!never_touch_scoped(
            home,
            &cache.join("clang/ModuleCache/module"),
            root
        ));
        for path in [
            cache.join("clang"),
            cache.join("org.llvm.clang/ModuleCache"),
            cache.join("com.apple.Safari"),
            cache.join("clang/ModuleCache/../other"),
            cache.join("clang/ModuleCache/Cookies"),
        ] {
            assert!(never_touch_scoped(home, &path, root));
        }
        assert!(never_touch_scoped(
            home,
            &cache.join("clang/ModuleCache"),
            None
        ));
    }
}
