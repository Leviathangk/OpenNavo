/// What inside a local model rule's path may be removed. Whole directories are only used where the directory holds
/// model weights alone; stores that mix models with chats, datasets or indexes list just the model entries.
#[derive(Debug, Clone, Copy)]
pub enum LocalModelScope {
    /// The rule path itself is a model-only directory.
    Directory,
    /// Only child directories whose names start with this prefix are model stores.
    Children(&'static str),
    /// Only regular files with one of these extensions (without the dot) are model files.
    Files(&'static [&'static str]),
}
