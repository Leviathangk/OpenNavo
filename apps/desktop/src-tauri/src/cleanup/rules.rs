/// Whether an item starts checked. Only the newest device support, anything downloaded again, installers,
/// the Trash, personal backups and Xcode archives start unchecked; everything else is offered.
pub fn default_selected(reason: CleanupReason) -> bool {
    !matches!(
        reason,
        CleanupReason::DeviceSupportLatest
            | CleanupReason::ToolDownloadCache
            | CleanupReason::Installer
            | CleanupReason::Trash
            | CleanupReason::DeviceBackup
            | CleanupReason::XcodeArchive
            | CleanupReason::LargeFile
            | CleanupReason::AiHistory
            | CleanupReason::AiHistoryFile
            | CleanupReason::LocalModel
            | CleanupReason::Worktree
            | CleanupReason::DuplicateCheckout
            | CleanupReason::OrphanWorktree
            | CleanupReason::BuildArtifact
    )
}
/// Whether the never-touch name rules apply below a candidate's root. Generated trees (build products, system
/// symbols, packages in node_modules, an app inside an archive) are full of names like Cursor, VPN or Docker that say
/// nothing about user secrets; there only the user's own protection rules apply. The root itself is always checked.
pub fn names_apply(reason: CleanupReason) -> bool {
    !matches!(
        reason,
        CleanupReason::ToolCache
            | CleanupReason::ToolDownloadCache
            | CleanupReason::DeviceSupport
            | CleanupReason::DeviceSupportLatest
            | CleanupReason::BuildArtifact
            | CleanupReason::BuildLeaf
            | CleanupReason::AiCache
            | CleanupReason::AiHistoryFile
            | CleanupReason::LocalModel
            | CleanupReason::DeviceBackup
            | CleanupReason::XcodeArchive
            | CleanupReason::Installer
            | CleanupReason::InstallerInstalled
            | CleanupReason::Trash
    )
}
/// Words in installer file names that never name the app ("Docker-arm64-universal-v4.30.dmg" is Docker).
const INSTALLER_NOISE: &[&str] = &[
    "universal",
    "arm64",
    "aarch64",
    "x64",
    "x86",
    "amd64",
    "intel",
    "apple",
    "silicon",
    "mac",
    "macos",
    "osx",
    "darwin",
    "setup",
    "installer",
    "install",
    "latest",
    "stable",
    "release",
    "beta",
    "signed",
    "dmg",
    "pkg",
];
fn compact(text: &str) -> String {
    text.chars()
        .filter(char::is_ascii_alphanumeric)
        .collect::<String>()
        .to_ascii_lowercase()
}
/// Whether an installer file name matches one of the installed app names (both compared without spaces, case and
/// version or platform words). Short names need an exact match so "go.pkg" never matches "Google".
pub fn installer_matches(stem: &str, apps: &[&str]) -> bool {
    let name: String = stem
        .split(|c: char| !c.is_ascii_alphanumeric())
        .map(str::to_ascii_lowercase)
        .filter(|t| !t.is_empty())
        .filter(|t| !INSTALLER_NOISE.contains(&t.as_str()))
        .filter(|t| !t.chars().all(|c| c.is_ascii_digit()))
        .filter(|t| {
            !(t.starts_with('v') && t[1..].chars().all(|c| c.is_ascii_digit()) && t.len() > 1)
        })
        .collect();
    if name.len() < 3 {
        return false;
    }
    apps.iter().map(|app| compact(app)).any(|app| {
        app == name
            || (app.len() >= 4
                && name.len() >= 4
                && (name.starts_with(&app) || app.starts_with(&name)))
    })
}
