fn compact(text: &str) -> String {
    text.chars()
        .filter(char::is_ascii_alphanumeric)
        .collect::<String>()
        .to_ascii_lowercase()
}
/// Whether an installer file name matches one of the installed app names (both compared without spaces, case and
/// version or platform words). Short names need an exact match so "go.pkg" never matches "Google".
pub fn installer_matches(stem: &str, apps: &[&str]) -> bool {
    let name: String = stem
        .split(|c: char| !c.is_ascii_alphanumeric())
        .map(str::to_ascii_lowercase)
        .filter(|t| !t.is_empty())
        .filter(|t| !INSTALLER_NOISE.contains(&t.as_str()))
        .filter(|t| !t.chars().all(|c| c.is_ascii_digit()))
        .filter(|t| {
            !(t.starts_with('v') && t[1..].chars().all(|c| c.is_ascii_digit()) && t.len() > 1)
        })
        .collect();
    if name.len() < 3 {
        return false;
    }
    apps.iter().map(|app| compact(app)).any(|app| {
        app == name
            || (app.len() >= 4
                && name.len() >= 4
                && (name.starts_with(&app) || app.starts_with(&name)))
    })
}
