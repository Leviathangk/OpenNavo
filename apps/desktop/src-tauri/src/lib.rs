pub async fn blocking<T: Send + 'static>(
    f: impl FnOnce() -> Result<T, AppError> + Send + 'static,
) -> Result<T, AppError> {
    tokio::task::spawn_blocking(f)
        .await
        .map_err(|e| AppError::new("E_UNKNOWN", "blocking_task").with_detail(e.to_string()))?
}

/// Export TS bindings to src/ipc/bindings.ts relative to src-tauri.
pub fn write_bindings(builder: &Builder<tauri::Wry>) -> Result<(), String> {
    builder
        .export(
            specta_typescript::Typescript::default().header(BINDINGS_HEADER),
            "../src/ipc/bindings.ts",
        )
        .map_err(|error| error.to_string())?;
    // Specta can leave trailing spaces when wrapping long union types.
    let path = "../src/ipc/bindings.ts";
    let generated = std::fs::read_to_string(path).map_err(|error| error.to_string())?;
    let normalized = generated
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    std::fs::write(path, normalized).map_err(|error| error.to_string())
}

/// A Finder-launched app gets a soft limit of 256 open files. Cleanup walks and removes folders on several threads,
/// each keeping one descriptor per folder level open, so the soft limit is raised toward the hard one.
pub fn raise_open_file_limit() {
    #[cfg(unix)]
    {
        use nix::libc;
        let mut limit = libc::rlimit {
            rlim_cur: 0,
            rlim_max: 0,
        };
        if unsafe { libc::getrlimit(libc::RLIMIT_NOFILE, &mut limit) } != 0 {
            return;
        }
        // macOS rejects a soft limit above OPEN_MAX (10240) even when the hard limit is unlimited.
        let wanted = limit.rlim_max.min(10_240);
        if limit.rlim_cur < wanted {
            limit.rlim_cur = wanted;
            unsafe { libc::setrlimit(libc::RLIMIT_NOFILE, &limit) };
        }
    }
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    raise_open_file_limit();
    let specta = specta_builder();
    let hidden = lifecycle::hidden_launch(&std::env::args().collect::<Vec<_>>());

    // Export bindings synchronously on development startup to match frontend types and commands; failure does not prevent running.
    #[cfg(debug_assertions)]
    if let Err(error) = write_bindings(&specta) {
        eprintln!("Failed to export IPC bindings: {error}");
    }

    let result = tauri::Builder::default()
        // Register single-instance first: a second instance forwards arguments including deep links to the running instance and exits (06 §4.3).
        .plugin(tauri_plugin_single_instance::init(|app, argv, _cwd| {
            if let Some(router) = app.try_state::<std::sync::Arc<deeplink::Router>>() {
                router.receive_args(&argv);
            } else {
                deeplink::show_main(app);
            }
        }))
        .plugin(tauri_plugin_deep_link::init())
        .plugin(tauri_plugin_updater::Builder::new().build())
        // Log Info and above by default; window/WebView debug logs are too noisy for log files.
        .plugin(
            tauri_plugin_log::Builder::new()
                .level(log::LevelFilter::Info)
                .level_for("tao", log::LevelFilter::Warn)
                .level_for("wry", log::LevelFilter::Warn)
                .build(),
        )
        .plugin(
            tauri_plugin_window_state::Builder::new()
                .with_state_flags(lifecycle::window_state_flags(hidden))
                .with_denylist(&[tray::LABEL, monitor::POPOVER_LABEL, firewall::ALERT_LABEL])
                .build(),
        )
        .plugin(tauri_plugin_store::Builder::new().build())
        .plugin(tauri_plugin_notification::init())
        // Login startup uses --hidden, creating only the tray without showing the main window (06 §4.3).
        .plugin(tauri_plugin_autostart::init(
            tauri_plugin_autostart::MacosLauncher::LaunchAgent,
            Some(vec![lifecycle::LOGIN_ARG]),
        ))
        .plugin(tauri_plugin_positioner::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_clipboard_manager::init())
        .plugin(tauri_plugin_process::init())
        // Replace command handlers before window creation; preserve official plugin permissions/JS APIs and check tasks before restart.
        .plugin(lifecycle::guarded_process())
        .plugin(tauri_plugin_os::init())
        .invoke_handler(specta.invoke_handler())
        .on_window_event(|window, event| {
            if matches!(event, tauri::WindowEvent::Focused(true)) {
                if let Some(sampler) =
                    window.try_state::<std::sync::Arc<monitor::sampler::Sampler>>()
                {
                    sampler
                        .set_window_visible(window.label(), window.is_visible().unwrap_or(false));
                }
                commands::settings::refresh_system(window.app_handle());
            }
            // macOS switched between light and dark while the appearance follows the system.
            if window.label() == "main" && matches!(event, tauri::WindowEvent::ThemeChanged(_)) {
                settings::sync_main_background(window.app_handle());
            }
            if window.label() == "main"
                && let tauri::WindowEvent::CloseRequested { api, .. } = event
            {
                // Keep the window until confirmation finishes; hidden windows can still be restored by tray, notifications, or deep links.
                api.prevent_close();
                let action = window
                    .try_state::<std::sync::Arc<core::DesktopCore>>()
                    .and_then(|core| core.current_settings().ok())
                    .map(|settings| lifecycle::close_action(&settings))
                    .unwrap_or(lifecycle::CloseAction::Hide);
                match action {
                    lifecycle::CloseAction::Hide => {
                        if window.hide().is_ok()
                            && let Some(sampler) =
                                window.try_state::<std::sync::Arc<monitor::sampler::Sampler>>()
                        {
                            sampler.set_window_visible(window.label(), false);
                        }
                    }
                    lifecycle::CloseAction::RequestExit => window.app_handle().exit(0),
                }
            }
        })
        .on_page_load(|webview, payload| {
            if webview.label() != "main" {
                return;
            }
            if let Some(router) = webview.try_state::<std::sync::Arc<deeplink::Router>>() {
                match payload.event() {
                    tauri::webview::PageLoadEvent::Started => router.loading(),
                    tauri::webview::PageLoadEvent::Finished => {
                        let router = router.inner().clone();
                        tauri::async_runtime::spawn(async move {
                            tokio::time::sleep(std::time::Duration::from_millis(250)).await;
                            router.ready();
                        });
                    }
                }
            }
        })
        .setup(move |app| {
            specta.mount_events(app);
            let data = app.path().app_data_dir()?;
            let cache = app.path().app_cache_dir()?;
            let askpass = app.path().resolve(
                "resources/askpass/opennavo-askpass",
                tauri::path::BaseDirectory::Resource,
            )?;
            let sink = events::sink(app.handle().clone());
            let core_sink = sink.clone();
            let core = tauri::async_runtime::block_on(blocking(move || {
                core::DesktopCore::open(data, cache, askpass, core_sink)
            }))?;
            #[cfg(target_os = "macos")]
            if relaunch::self_heal(app.handle(), &core, hidden) {
                return Ok(());
            }
            deeplink::install(app.handle(), sink);
            let app_handle = app.handle().clone();
            let store_path = core.data_dir.join("settings.json");
            let save = tauri::async_runtime::block_on(blocking(move || {
                settings::plugin_save(&app_handle, &store_path)
            }))?;
            core.install_settings_save(save)?;
            app.manage(core.clone());
            app.manage(std::sync::Arc::new(guide::Guide::default()));
            // Tauri builds the config-defined main window before this closure runs. Apply the saved appearance before
            // lifecycle can show that window, so a forced light or dark start never flashes the other theme.
            settings::apply_appearance(app.handle(), core.current_settings()?.appearance);
            lifecycle::install(app.handle(), hidden);
            let notifications = notifications::NativeNotifications::new(app.handle().clone());
            let weak = std::sync::Arc::downgrade(&notifications);
            let weak_core = std::sync::Arc::downgrade(&core);
            core.install_notice_sink(std::sync::Arc::new(move |notice| {
                if let (Some(native), Some(core)) = (weak.upgrade(), weak_core.upgrade())
                    && let Ok(settings) = core.current_settings()
                    && let Err(error) = native.send(notice, settings.locale)
                {
                    log::info!(
                        "System notifications temporarily unavailable: {}",
                        error.code
                    );
                }
            }))?;
            app.manage(notifications);
            settings::apply_apple_languages(&core.current_settings()?);
            settings::install_locale_observer(app.handle());
            native_menu::install(app.handle(), core.current_settings()?.locale)?;
            tray::install(app.handle())?;
            if let Err(error) = monitor::install(app.handle()) {
                log::warn!("Monitor unavailable: {}", error.code);
            }
            core.queue.start();
            core.start_catalog_sync();
            core.start_library_scan();
            uninstall::install_watch(app.handle());
            security::watch::install(app.handle());
            firewall::install(app.handle(), &core);
            scheduler::start(&core);
            usage::start(&core, app.package_info().version.to_string());
            Ok(())
        })
        .build(tauri::generate_context!());

    // Runtime initialization fails only during startup (configuration/system resources); continuing is impossible, so exit.
    match result {
        Ok(app) => app.run(lifecycle::run_event),
        Err(error) => {
            eprintln!("OpenNavo startup failed: {error}");
            std::process::exit(1);
        }
    }
}

/// The root-level name matches gen's --exact filter, avoiding successful commands that run zero tests.
#[cfg(test)]
#[test]
fn export_bindings() {
    write_bindings(&specta_builder()).expect("binding export must succeed");
    let bindings = std::fs::read_to_string("../src/ipc/bindings.ts").unwrap();
    for expected in [
        "permissionSettingsOpen: (pane: PrivacyPane)",
        "relaunchIneffective: boolean",
        "monitorSubscribe: (view: MonitorView, modules: MonitorModule[])",
        "monitorTrend:",
        "export type MonitorTrendPoint =",
        "export type DiskDevice =",
        "export type MenuBarStyle = \"text\" | \"value\" | \"line\" | \"bars\"",
        "powerWatts: number | null",
        "diskReadBytesPerSec: number | null",
        "diskWriteBytesPerSec: number | null",
        "netDownBytesPerSec: number | null",
        "netUpBytesPerSec: number | null",
        "devices: DiskDevice[] | null",
        "subject: string | null",
        "monitorOpenInMain: (target: MonitorMainTarget, module:",
        "export type FanControlSupport =",
        "manualAllowed: boolean",
        "monitorIntervalMs: 1000 | 2000 | 5000",
        "monitorMenuBar: MonitorMenuBar",
        "fanLastManual:",
        "monitor:sample",
        "monitor:popover",
        "fan:changed",
        "fanHelperOpenApproval:",
        "load: [number, number, number]",
        "usage: number,",
        "cores: number[]",
        "celsius: number,",
        "localIp: string | null",
        "gpu: GpuSample | null",
    ] {
        assert!(
            bindings.contains(expected),
            "missing monitor IPC export: {expected}"
        );
    }
    assert!(!bindings.contains("monitorMenuBar?:"));
    assert!(!bindings.contains("manualAllowed?:"));
    assert!(bindings.contains("\ttrashedBytes: number,"));
    assert!(bindings.contains("\tvolume: CleanupVolume | null,"));
    assert!(!bindings.contains("trashedBytes?:"));
    for removed in [
        "leftoversScan:",
        "leftoversRemove:",
        "cleanupEstimate:",
        "export type LeftoverReport",
        "export type LeftoverGroup",
        "export type BrewCleanupItem",
        "export type CleanupEstimate",
    ] {
        assert!(!bindings.contains(removed), "removed IPC export: {removed}");
    }
}
