-- The receipt token lets an anonymous developer read their submission status
-- without an account. It is random and independent from the sequential id.
ALTER TABLE developer_submissions ADD COLUMN public_token TEXT;
UPDATE developer_submissions
SET public_token = md5(random()::text || clock_timestamp()::text || id::text)
WHERE public_token IS NULL;
ALTER TABLE developer_submissions ALTER COLUMN public_token SET NOT NULL;
CREATE UNIQUE INDEX developer_submissions_public_token ON developer_submissions (public_token);

-- Status history is shown on the public status page and in the admin drawer.
CREATE TABLE developer_submission_events (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id BIGINT NOT NULL REFERENCES developer_submissions(id) ON DELETE CASCADE,
  status        TEXT NOT NULL,
  note          TEXT,
  actor         TEXT NOT NULL DEFAULT 'system' CHECK (actor IN ('developer', 'admin', 'system')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX developer_submission_events_submission ON developer_submission_events (submission_id, created_at);

