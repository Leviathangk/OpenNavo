-- Evidence-backed extensions to the legacy package_facts contract. Stable IDs may be referenced
-- by the SEO and automation migrations; sources and expiry are required, never inferred at read time.
CREATE TABLE package_fact_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 package_id BIGINT NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
 kind TEXT NOT NULL CHECK (kind IN ('price','security','attribute','migration','compatibility','issue','integration')),
 key TEXT NOT NULL CHECK (length(key) BETWEEN 1 AND 160),
 value JSONB NOT NULL CHECK (jsonb_typeof(value)='object'),
 evidence JSONB NOT NULL CHECK (jsonb_typeof(evidence)='object' AND evidence->>'sourceUrl' LIKE 'https://%'
  AND evidence->>'status' IN ('verified','needs_review') AND evidence ? 'checkedAt' AND evidence ? 'validUntil'),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(package_id,kind,key)
);
CREATE UNIQUE INDEX package_price_dimensions ON package_fact_records
 (package_id,(value->>'region'),(value->>'edition'),(value->>'period'),(value->>'channel')) WHERE kind='price';

