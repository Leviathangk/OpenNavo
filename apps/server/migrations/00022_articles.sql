-- WP14 articles. An article row is identity and lifecycle; everything readers see (text, type,
-- author, cover, sources, related apps) lives in a revision. Edits to a published article form a
-- new working revision and never change the live page until someone with publish permission
-- publishes it. Translations belong to one revision, so a late translation of an old revision
-- cannot overwrite a newer one, and the public API only reads the published revision.

CREATE TABLE article_authors (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 80),
 name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
 links JSONB NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(links)='array'),
 avatar_asset_id BIGINT REFERENCES assets(id) ON DELETE SET NULL,
 source_locale TEXT NOT NULL DEFAULT 'en-US' CHECK (source_locale IN ('en-US','zh-CN','ja-JP','es-ES','pt-BR','ru-RU')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE article_author_i18n (
 author_id BIGINT NOT NULL REFERENCES article_authors(id) ON DELETE CASCADE,
 locale TEXT NOT NULL CHECK (locale IN ('en-US','zh-CN','ja-JP','es-ES','pt-BR','ru-RU')),
 role TEXT CHECK (role IS NULL OR length(role) <= 80),
 bio TEXT CHECK (bio IS NULL OR length(bio) <= 1000),
 status TEXT NOT NULL DEFAULT 'manual' CHECK (status IN ('source','machine','manual','pending','failed')),
 source_locale TEXT NOT NULL DEFAULT 'en-US' CHECK (source_locale IN ('en-US','zh-CN','ja-JP','es-ES','pt-BR','ru-RU')),
 source_hash TEXT,
 model TEXT,
 translated_at TIMESTAMPTZ,
 fail_reason TEXT,
 machine_translated BOOLEAN NOT NULL DEFAULT false,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY (author_id, locale)
);
CREATE TRIGGER translation_provenance BEFORE INSERT OR UPDATE OF status ON article_author_i18n FOR EACH ROW EXECUTE FUNCTION preserve_translation_provenance();

CREATE TABLE articles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 100),
 -- draft/review: never published; published: live; archived: withdrawn, restorable.
 status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','review','published','archived')),
 working_revision_id BIGINT NOT NULL,
 published_revision_id BIGINT,
 -- Idempotency key for creation: the same key returns the same article.
 client_key TEXT UNIQUE CHECK (client_key IS NULL OR length(client_key) BETWEEN 1 AND 128),
 -- Set once, at the first publication; content_updated_at moves only when a substantive change is published.
 first_published_at TIMESTAMPTZ,
 content_updated_at TIMESTAMPTZ,
 archived_at TIMESTAMPTZ,
 -- Bumped by every change; writes carry it as expectedRevision so concurrent edits cannot overwrite each other.
 revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
 created_by BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((status IN ('published','archived')) = (published_revision_id IS NOT NULL AND first_published_at IS NOT NULL)),
 CHECK ((status = 'archived') = (archived_at IS NOT NULL))
);

CREATE TABLE article_revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
 number INTEGER NOT NULL CHECK (number > 0),
 source_locale TEXT NOT NULL CHECK (source_locale IN ('en-US','zh-CN','ja-JP','es-ES','pt-BR','ru-RU')),
 type TEXT NOT NULL CHECK (type IN ('recommendation','review','tutorial','roundup','news')),
 -- NULL author is the editorial byline (the site organization).
 author_id BIGINT REFERENCES article_authors(id) ON DELETE SET NULL,
 cover_asset_id BIGINT REFERENCES assets(id) ON DELETE SET NULL,
 cover_alt TEXT CHECK (cover_alt IS NULL OR length(cover_alt) BETWEEN 1 AND 300),
 sources JSONB NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(sources)='array'),
 -- Hash of what readers see; dateModified moves only when a published revision changes it.
 content_hash TEXT NOT NULL DEFAULT '',
 submitted_at TIMESTAMPTZ,
 submitted_by BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
 submitted_by_name TEXT NOT NULL DEFAULT '',
 published_at TIMESTAMPTZ,
 created_by BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
 created_by_name TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE (article_id, number),
 CHECK (cover_asset_id IS NULL OR cover_alt IS NOT NULL)
);
ALTER TABLE articles ADD CONSTRAINT articles_working_revision FOREIGN KEY (working_revision_id) REFERENCES article_revisions(id) DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE articles ADD CONSTRAINT articles_published_revision FOREIGN KEY (published_revision_id) REFERENCES article_revisions(id) DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE article_revision_i18n (
 revision_id BIGINT NOT NULL REFERENCES article_revisions(id) ON DELETE CASCADE,
 locale TEXT NOT NULL CHECK (locale IN ('en-US','zh-CN','ja-JP','es-ES','pt-BR','ru-RU')),
 title TEXT NOT NULL DEFAULT '' CHECK (length(title) <= 200),
 summary TEXT CHECK (summary IS NULL OR length(summary) <= 400),
 body_markdown TEXT CHECK (body_markdown IS NULL OR length(body_markdown) <= 100000),
 test_note TEXT CHECK (test_note IS NULL OR length(test_note) <= 1000),
 seo_title TEXT CHECK (seo_title IS NULL OR length(seo_title) <= 120),
 seo_description TEXT CHECK (seo_description IS NULL OR length(seo_description) <= 300),
 status TEXT NOT NULL DEFAULT 'manual' CHECK (status IN ('source','machine','manual','pending','failed')),
 source_locale TEXT NOT NULL CHECK (source_locale IN ('en-US','zh-CN','ja-JP','es-ES','pt-BR','ru-RU')),
 source_hash TEXT,
 model TEXT,
 translated_at TIMESTAMPTZ,
 fail_reason TEXT,
 machine_translated BOOLEAN NOT NULL DEFAULT false,
 -- A language held back by an editor stays off the site even when its translation is ready.
 withheld BOOLEAN NOT NULL DEFAULT false,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY (revision_id, locale)
);
CREATE TRIGGER translation_provenance BEFORE INSERT OR UPDATE OF status ON article_revision_i18n FOR EACH ROW EXECUTE FUNCTION preserve_translation_provenance();

CREATE TABLE article_revision_packages (
 revision_id BIGINT NOT NULL REFERENCES article_revisions(id) ON DELETE CASCADE,
 package_id BIGINT NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
 sort SMALLINT NOT NULL CHECK (sort BETWEEN 0 AND 49),
 PRIMARY KEY (revision_id, package_id)
);
CREATE INDEX article_revision_packages_package ON article_revision_packages(package_id);

-- Former slugs redirect to the article.
CREATE TABLE article_slug_aliases (
 slug TEXT PRIMARY KEY CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 100),
 article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Review record: submissions, invalidated reviews, publications, withdrawals and restores.
CREATE TABLE article_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
 revision_number INTEGER,
 action TEXT NOT NULL CHECK (action IN ('create','update','submit','review_invalidated','publish','withdraw','restore','slug','withhold','release','revert')),
 actor_type TEXT NOT NULL CHECK (actor_type IN ('admin','agent','system')),
 actor_id BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
 actor_name TEXT NOT NULL DEFAULT '',
 detail JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(detail)='object'),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX article_events_article ON article_events(article_id, id DESC);

