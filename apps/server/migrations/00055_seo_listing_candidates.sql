DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM seo_listing_candidates) OR EXISTS(SELECT 1 FROM seo_listing_baselines) THEN
  RAISE EXCEPTION 'Archive and explicitly resolve publication evidence before rolling back';
 END IF;
END $$;
-- +goose StatementEnd
DROP TRIGGER automatic_listing_package ON packages;
