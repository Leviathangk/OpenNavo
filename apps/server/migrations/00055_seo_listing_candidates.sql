-- +goose Up
-- A candidate has no packages row. Public queries cannot accidentally expose it.
CREATE TABLE seo_listing_baselines (
 package_id BIGINT PRIMARY KEY REFERENCES packages(id) ON DELETE RESTRICT,
 domain TEXT NOT NULL,
 developer TEXT NOT NULL,
 team_id TEXT NOT NULL CHECK (team_id ~ '^[A-Z0-9]{10}$'),
 fact_id BIGINT NOT NULL,
 evidence_id BIGINT NOT NULL,
 evidence_hash TEXT NOT NULL,
 verified_by BIGINT NOT NULL REFERENCES admin_users(id),
 verified_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 valid_until TIMESTAMPTZ NOT NULL,
 suspicious BOOLEAN NOT NULL DEFAULT false
);
CREATE TABLE seo_listing_candidates (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 token TEXT NOT NULL UNIQUE CHECK (token ~ '^[a-z0-9][a-z0-9+@._-]{0,127}$'),
 state TEXT NOT NULL DEFAULT 'candidate' CHECK (state IN ('candidate','published','rejected')),
 revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
 payload JSONB NOT NULL CHECK (jsonb_typeof(payload)='object'),
 baseline_package_id BIGINT REFERENCES packages(id) ON DELETE RESTRICT,
 package_id BIGINT UNIQUE REFERENCES packages(id) ON DELETE RESTRICT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((state='published') = (package_id IS NOT NULL))
);
-- Defense in depth for legacy restoration and catalog writers. Automatic link apps
-- cannot acquire an installer URL or a release-asset source via a different API.
-- +goose StatementBegin
CREATE FUNCTION protect_automatic_listing_download() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE c JSONB;
BEGIN
 SELECT payload INTO c FROM seo_listing_candidates WHERE package_id=NEW.package_id AND state='published';
 IF c IS NOT NULL AND (
  NEW.homepage IS DISTINCT FROM c->'link'->>'homepage' OR
  NEW.download_url IS DISTINCT FROM c->'link'->>'downloadUrl' OR
  NEW.team_id IS DISTINCT FROM c->'link'->>'teamId' OR
  to_jsonb(NEW.bundle_ids) IS DISTINCT FROM COALESCE(c->'link'->'bundleIds','[]'::jsonb) OR
  NEW.github_repo IS NOT NULL OR NEW.sparkle_feed IS NOT NULL OR
  (NEW.asset_rules IS NOT NULL AND NEW.asset_rules NOT IN ('null'::jsonb,'{}'::jsonb)) OR NEW.latest IS NOT NULL
 ) THEN RAISE EXCEPTION 'automatic listing identity/download requires revalidation' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
-- +goose StatementEnd
CREATE TRIGGER automatic_listing_download BEFORE INSERT OR UPDATE ON link_apps FOR EACH ROW EXECUTE FUNCTION protect_automatic_listing_download();

-- +goose StatementBegin
CREATE FUNCTION protect_automatic_listing_package() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE c JSONB;
BEGIN
 -- Homebrew adoption is allowed to assume catalog ownership under its own checks.
 IF NEW.kind <> 'link' THEN RETURN NEW; END IF;
 SELECT payload INTO c FROM seo_listing_candidates WHERE package_id=NEW.id AND state='published';
 IF c IS NOT NULL AND (NEW.token IS DISTINCT FROM c->'link'->>'token' OR NEW.name IS DISTINCT FROM c->'link'->>'name' OR NEW.homepage IS DISTINCT FROM c->'link'->>'homepage' OR NEW.download_url IS DISTINCT FROM c->'link'->>'downloadUrl') THEN
  RAISE EXCEPTION 'automatic listing identity requires revalidation' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
-- +goose StatementEnd
CREATE TRIGGER automatic_listing_package BEFORE UPDATE ON packages FOR EACH ROW EXECUTE FUNCTION protect_automatic_listing_package();

-- +goose Down
-- Never erase identity/publication evidence as an implicit schema rollback.
