-- +goose Up
-- Developer map locations are recorded per App (not per developer/company).
CREATE TABLE package_locations (
  package_id    BIGINT PRIMARY KEY REFERENCES packages(id) ON DELETE CASCADE,
  country_code  CHAR(2) NOT NULL CHECK (country_code ~ '^[A-Z]{2}$'),
  city          TEXT,
  city_key      TEXT,
  region        TEXT NOT NULL DEFAULT 'other' CHECK (region IN ('americas', 'europe', 'apac', 'other')),
  lat           DOUBLE PRECISION,
  lng           DOUBLE PRECISION,
  remote        BOOLEAN NOT NULL DEFAULT FALSE,
  source        TEXT NOT NULL DEFAULT 'admin' CHECK (source IN ('admin', 'self', 'import')),
  status        TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('approved', 'pending', 'rejected')),
  confidence    TEXT NOT NULL DEFAULT 'self_reported' CHECK (confidence IN ('verified', 'self_reported', 'probable')),
  evidence_url  TEXT,
  verified_by   BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
  verified_at   TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX package_locations_status ON package_locations (status, country_code);
CREATE INDEX package_locations_city ON package_locations (city_key) WHERE status = 'approved';

-- Developer submissions are leads: an editor reviews them and then creates/updates
-- the package with the existing catalog tools. They never publish directly.
CREATE TABLE developer_submissions (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind           TEXT NOT NULL CHECK (kind IN ('new', 'claim', 'location')),
  status         TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'in_review', 'changes_requested', 'approved', 'rejected', 'published')),
  source_kind    TEXT,
  source_url     TEXT,
  package_id     BIGINT REFERENCES packages(id) ON DELETE SET NULL,
  payload        JSONB NOT NULL DEFAULT '{}'::jsonb,
  contact_email  TEXT NOT NULL,
  proof          TEXT,
  reviewer_id    BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
  decision_note  TEXT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_at     TIMESTAMPTZ
);
CREATE INDEX developer_submissions_status ON developer_submissions (status, created_at DESC);

-- A published developer submission can be featured in Discover, above Hot Apps.
CREATE TABLE developer_picks (
  package_id    BIGINT PRIMARY KEY REFERENCES packages(id) ON DELETE CASCADE,
  submission_id BIGINT REFERENCES developer_submissions(id) ON DELETE SET NULL,
  quote         TEXT,
  sort          INTEGER NOT NULL DEFAULT 0,
  active        BOOLEAN NOT NULL DEFAULT TRUE,
  published_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX developer_picks_active ON developer_picks (active, sort, published_at DESC);

