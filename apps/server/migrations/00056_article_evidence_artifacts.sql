-- A merge can remap package_id; the actual report, its original identity and hash
-- remain immutable. Evidence IDs live in JSON until H2's later migration exists.
-- +goose StatementBegin
CREATE FUNCTION protect_article_test_artifact() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.article_id IS DISTINCT FROM OLD.article_id OR NEW.payload IS DISTINCT FROM OLD.payload OR NEW.sha256 IS DISTINCT FROM OLD.sha256 OR NEW.registered_by IS DISTINCT FROM OLD.registered_by OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
 RAISE EXCEPTION 'test artifacts are immutable' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
-- +goose StatementEnd
CREATE TRIGGER article_test_artifact_immutable BEFORE UPDATE ON article_test_artifacts FOR EACH ROW EXECUTE FUNCTION protect_article_test_artifact();

